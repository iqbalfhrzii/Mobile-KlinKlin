import '../../../core/api/api_client.dart';
import 'package:dio/dio.dart';

class OperasionalLayananKesehatanService {
  final Dio _apiClient = ApiClient.instance;

  Future<Map<String, dynamic>> getLayananKesehatan({
    String? search,
    String? cabangId,
    int page = 1,
  }) async {
    try {
      final queryParams = <String, dynamic>{'page': page};
      if (search != null && search.isNotEmpty) queryParams['search'] = search;
      if (cabangId != null && cabangId != 'all') queryParams['cabang_id'] = cabangId;

      final response = await _apiClient.get(
        '/operasional/layanan-kesehatan',
        queryParameters: queryParams,
      );
      
      return response.data;
    } on DioException catch (e) {
      return {
        'status': false,
        'message': e.response?.data['message'] ?? e.message,
      };
    } catch (e) {
      return {
        'status': false,
        'message': e.toString(),
      };
    }
  }

  Future<Map<String, dynamic>> storeLayananKesehatan(Map<String, dynamic> data) async {
    try {
      final response = await _apiClient.post(
        '/operasional/layanan-kesehatan', 
        data: data,
      );
      return response.data;
    } on DioException catch (e) {
      return {
        'status': false,
        'message': e.response?.data['message'] ?? e.message,
      };
    } catch (e) {
      return {
        'status': false,
        'message': e.toString(),
      };
    }
  }

  Future<Map<String, dynamic>> updateLayananKesehatan(int id, Map<String, dynamic> data) async {
    try {
      final response = await _apiClient.put(
        '/operasional/layanan-kesehatan/$id', 
        data: data,
      );
      return response.data;
    } on DioException catch (e) {
      return {
        'status': false,
        'message': e.response?.data['message'] ?? e.message,
      };
    } catch (e) {
      return {
        'status': false,
        'message': e.toString(),
      };
    }
  }

  Future<Map<String, dynamic>> deleteLayananKesehatan(int id) async {
    try {
      final response = await _apiClient.delete('/operasional/layanan-kesehatan/$id');
      return response.data;
    } on DioException catch (e) {
      return {
        'status': false,
        'message': e.response?.data['message'] ?? e.message,
      };
    } catch (e) {
      return {
        'status': false,
        'message': e.toString(),
      };
    }
  }
}
